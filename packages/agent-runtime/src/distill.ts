/**
 * Distill-on-Accept — rule-template → knowledge body (M3 first version).
 * No embeddings; plain Markdown for M4 retrieval later.
 */

export type DistillInput = {
  sessionId: string;
  pageUrl: string;
  annotationNote?: string | null;
  selector?: string | null;
  sniffSummary?: string | null;
  patch?: string | null;
  actSummary?: string | null;
};

export type DistillResult = {
  kind: "pattern";
  title: string;
  body_md: string;
};

export function distillOnAccept(input: DistillInput): DistillResult {
  const selector = input.selector?.trim() || "(unspecified selector)";
  const note = input.annotationNote?.trim() || "(no note)";
  const title = `Fix pattern: ${selector}`.slice(0, 180);

  const body = [
    `# ${title}`,
    "",
    `- **session:** \`${input.sessionId}\``,
    `- **page:** ${input.pageUrl}`,
    `- **selector:** \`${selector}\``,
    `- **annotation:** ${note}`,
    "",
    "## What worked",
    "",
    input.actSummary?.trim() ||
      "Accepted a temporary agent commit after retrieve → act → verify.",
    "",
    "## Sniff context",
    "",
    "```",
    (input.sniffSummary ?? "").slice(0, 2000) || "(none)",
    "```",
    "",
    "## Diff excerpt",
    "",
    "```diff",
    (input.patch ?? "").slice(0, 4000) || "(empty)",
    "```",
    "",
    "_Generated by SightLoop Distill-on-Accept (rule template v1)._",
    "",
  ].join("\n");

  return { kind: "pattern", title, body_md: body };
}
